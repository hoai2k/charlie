"""Measure each doll's throwing hand and write ../../hands.js.

For every doll sheet (and her skates/pogo sheet when delivered) this finds the
forward-most opaque point in the upper body of the pose used when pushing or
throwing: standing push (sprites row 4 cell 2), seated rider (sprites row 4
cell 1, used on mounts), skate push (toys row 2 cell 2) and pogo push (toys
row 4 cell 2). Coordinates are frame pixels, facing right. The game starts a
thrown snowball at that hand.

Run after adding a doll or a toys sheet:  python3 tools/dolls/measure_hands.py
"""
import json, re
from pathlib import Path
import numpy as np
from PIL import Image

GAME = Path(__file__).resolve().parents[2]
F = 418


def hand(cell):
    a = np.asarray(cell.convert('RGBA'))[..., 3] > 40
    ys, xs = np.nonzero(a)
    if len(xs) == 0:
        return None
    top, h = ys.min(), ys.max() - ys.min()
    band = (ys > top + 0.18 * h) & (ys < top + 0.6 * h)
    i = int(np.argmax(np.where(band, xs, -1)))
    return [int(xs[i]), int(ys[i])]


def cell(img, row, col):
    return img.crop((col * F, row * F, (col + 1) * F, (row + 1) * F))


def asset_keys():
    keys = ['whirlpool', 'juliette', 'claudia', 'kaya', 'lily', 'marisol', 'amanda', 'penelope', 'rumi']
    dolls = json.loads(re.search(r'window\.EXTRA_DOLLS = (\{.*?\n\});', (GAME / 'dolls.js').read_text(), re.S).group(1))
    keys += [d.get('assetKey', k) for k, d in dolls.items()]
    return sorted(set(keys))


out = {}
for key in asset_keys():
    sheet_path = GAME / f'assets/doll_{key}_sprites.webp'
    if not sheet_path.exists():
        continue
    sheet = Image.open(sheet_path)
    entry = {'stand': hand(cell(sheet, 3, 1)), 'ride': hand(cell(sheet, 3, 0))}
    toys_path = GAME / f'assets/doll_{key}_toys.webp'
    if toys_path.exists():
        toys = Image.open(toys_path)
        entry['skate'] = hand(cell(toys, 1, 1))
        entry['pogo'] = hand(cell(toys, 3, 1))
    out[key] = entry

(GAME / 'hands.js').write_text('// Generated by tools/dolls/measure_hands.py: each doll\'s throwing hand\n'
                               '// (frame pixels, facing right) per pose.\n'
                               'window.DOLL_HANDS = ' + json.dumps(out, indent=1) + ';\n')
print(json.dumps(out))
