"""Write ../../pose-shapes.js: each doll pose's leg silhouette, small.

For every frame of each doll's sprites and actions sheets: the lower half of
her figure (her legs and feet), in a square box on her legs, shrunk to 16x16
and stored as 64 hex digits (one bit a pixel). The game compares these to
find, for a pose, the poses on other dolls that look most like it, so moon
boots placed by hand on one doll carry over to a pose like it on another
(game-draw.js learnedMoonBootView).

Run after adding a doll or redrawing poses:  python3 tools/dolls/measure_poses.py
"""
import json
from pathlib import Path
import numpy as np
from PIL import Image
from measure_feet import asset_keys

GAME = Path(__file__).resolve().parents[2]
F = 418
N = 16


def legs(cell):
    a = np.asarray(cell.convert('RGBA'))[:, :, 3] > 60
    ys, xs = np.nonzero(a)
    if not len(ys):
        return None
    top, bottom = ys.min(), ys.max()
    band = a[int(top + 0.5 * (bottom - top)):bottom + 1]
    lx = np.nonzero(band.any(0))[0]
    side = max(band.shape[0], lx.max() - lx.min() + 1)
    box = np.zeros((side, side), bool)
    x0 = (lx.min() + lx.max()) // 2 - side // 2
    for x in range(side):
        if 0 <= x0 + x < F:
            box[side - band.shape[0]:, x] = band[:, x0 + x]
    small = np.asarray(Image.fromarray(box.astype(np.uint8) * 255).resize((N, N), Image.BILINEAR)) > 127
    return ''.join(f'{int("".join("1" if b else "0" for b in row[i:i + 4]), 2):x}' for row in small for i in range(0, N, 4))


def sheet(path):
    if not path.exists():
        return None
    im = Image.open(path)
    rows, cols = im.height // F, im.width // F
    return [legs(im.crop((c * F, r * F, (c + 1) * F, (r + 1) * F))) for r in range(rows) for c in range(cols)]


if __name__ == '__main__':
    out = {}
    for key in asset_keys():
        entry = {kind: sheet(GAME / f'assets/doll_{key}_{kind}.webp') for kind in ('sprites', 'actions')}
        if entry['sprites']:
            out[key] = entry
    (GAME / 'pose-shapes.js').write_text(
        "// Generated by tools/dolls/measure_poses.py: each doll pose's leg silhouette\n"
        "// (16x16 bits as 64 hex digits), to match poses between dolls.\n"
        'window.DOLL_POSE_SHAPES = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    print(len(out), 'dolls')
