"""Export one reusable broom prop and the roster's measured hand anchors."""
import hashlib
import json
import sys
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
GAME = HERE.parents[1]


def build():
    spec = json.loads((HERE / 'broom.json').read_text())
    image = Image.open(HERE / 'sources/broom-canonical.webp').convert('RGBA')
    image.putalpha(image.getchannel('A').point(lambda a: 0 if a < 4 else a))
    image = image.crop(image.getchannel('A').getbbox())
    image.thumbnail((720, 180), Image.Resampling.LANCZOS)
    target = GAME / spec['asset']
    image.save(target, lossless=True, method=6)
    spec['size'] = list(image.size)
    spec['sha256'] = hashlib.sha256(target.read_bytes()).hexdigest()
    (HERE / 'broom.json').write_text(json.dumps(spec, indent=2) + '\n')
    data = {key: spec[key] for key in ['grip', 'carryHands']}
    (GAME / 'broom.js').write_text('// Generated by tools/mounts/build_broom.py. Hand anchors use 418px idle/run cells.\nwindow.BROOM_ART = ' + json.dumps(data, indent=2) + ';\n')


def check():
    spec = json.loads((HERE / 'broom.json').read_text())
    target = GAME / spec['asset']
    image = Image.open(target).convert('RGBA')
    assert list(image.size) == spec['size']
    assert image.getchannel('A').getextrema() == (0, 255)
    assert hashlib.sha256(target.read_bytes()).hexdigest() == spec['sha256']
    for rows in spec['carryHands'].values():
        assert len(rows) == 2
        for row in rows:
            assert len(row) == 3
            assert all(0 < x < 418 and 0 < y < 418 for x, y in row)
    print('Broom alpha, dimensions, hand anchors and SHA-256 passed')


if __name__ == '__main__':
    if '--check' not in sys.argv:
        build()
    check()
