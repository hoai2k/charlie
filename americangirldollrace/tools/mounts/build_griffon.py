"""Pack generated griffon strips and derive per-frame rider-seat calibration."""
import hashlib
import json
import sys
from pathlib import Path
from PIL import Image, ImageDraw
HERE = Path(__file__).resolve().parent
GAME = HERE.parents[1]
sys.path.insert(0, str(HERE.parent/'dolls'))
from build import bounds, split_strip, place, save_webp


def build():
    spec = json.loads((HERE/'griffon.json').read_text())
    sheet = Image.new('RGBA',(1254,1254))
    calibration, frames = [], []
    report = []
    for row, key in enumerate(['idle','run','jump']):
        src = Image.open(HERE/f'sources/griffon-{key}.webp').convert('RGBA')
        src.putalpha(src.getchannel('A').point(lambda a:0 if a<4 else a))
        calibration.append([])
        for col, box in enumerate(split_strip(src)):
            cell = src.crop(box)
            b = bounds(cell)
            assert b[0] > 0 and b[1] > 0 and b[2] < cell.width and b[3] < cell.height, (key,col,'source clipping')
            back_x, back_y = spec['seats'][row][col]
            back_x += col*src.height-box[0]
            frame, _, info = place(cell,Image.new('RGBA',cell.size),
                                   {'anchor':[back_x,b[3]],'target':[225,409]},spec['scale'])
            seat_y = round(409+(back_y-b[3])*spec['scale'],2)
            calibration[row].append([225,seat_y,0])
            frames.append(frame)
            report.append({'pose':f'{key}-{col}','bounds':info['bounds'],'seat':[225,seat_y], 'scale':spec['scale']})
            sheet.paste(frame,(col*418,row*418))
    save_webp(sheet,GAME/'assets/griffon_sprites.webp')
    (GAME/'mounts.js').write_text('// Generated by tools/mounts/build_griffon.py.\nwindow.MOUNT_ART = '+json.dumps({'griffon':{'calibration':calibration}},indent=2)+';\n')
    spec['sha256'] = hashlib.sha256((GAME/'assets/griffon_sprites.webp').read_bytes()).hexdigest()
    spec['frames'] = report
    (HERE/'griffon.json').write_text(json.dumps(spec,indent=2)+'\n')
    # Review the real mounted draw offsets with Hermione: her seat is [209,264].
    rider=Image.open(GAME/'assets/portraits/hermione_ride.webp').convert('RGBA').resize((293,293),Image.Resampling.LANCZOS)
    qa=Image.new('RGB',(1350,1530),'#c9e1d6'); d=ImageDraw.Draw(qa)
    for n, frame in enumerate(frames):
        x,y=n%3*450,n//3*510
        d.text((x+8,y+8),report[n]['pose'],fill='#203d38')
        mount=frame.resize((451,451),Image.Resampling.LANCZOS)
        qa.paste(mount,(x,y+40),mount)
        seat=report[n]['seat']; rx=round(x+225*1.08-209*.7);ry=round(y+40+seat[1]*1.08-264*.7)
        qa.paste(rider,(rx,ry),rider)
    qa.save(HERE/'griffon-review.jpg',quality=91)
    print('Griffon: nine 418px frames exported with shared scale and measured seat anchors')


def check():
    meta=json.loads((HERE/'griffon.json').read_text())
    path=GAME/'assets/griffon_sprites.webp'
    assert hashlib.sha256(path.read_bytes()).hexdigest()==meta['sha256']
    im=Image.open(path).convert('RGBA')
    assert im.size==(1254,1254) and im.getchannel('A').getextrema()==(0,255)
    for n,info in enumerate(meta['frames']):
        b=bounds(im.crop((n%3*418,n//3*418,n%3*418+418,n//3*418+418)))
        assert list(b)==info['bounds']
        assert b[0]>=5 and b[1]>=5 and b[2]<=413 and b[3]<=413
    print('Griffon dimensions, alpha, frame bounds and SHA-256 passed')


if __name__=='__main__':
    if '--check' not in sys.argv:
        build()
    check()
