"""Pack measured skeleton seats and separate troll riders into runtime cells."""
import json
import sys
from pathlib import Path
from PIL import Image
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'tracks'))
from build import clean,bounds,mount_cells,atlas_cells,save
HERE=Path(__file__).resolve().parent
GAME=HERE.parents[1]
# Coordinates measured on the source's nominal 418px cells.
HORSE_SEATS=[[199,220],[219,221],[198,222],[228,221],[218,222],[229,222],[219,231],[224,233],[226,231]]
REFERENCE_SEATS=[[199,230],[219,232],[198,233],[228,234],[218,219],[229,233],[219,231],[224,235],[226,228]]
# Troll source uses 512px cells; hips sit at the saddle, not at the feet.
TROLL_HIPS=[[273,315],[275,307],[265,318],[267,332],[275,326],[270,330]]


def build():
    source=clean(Image.open(HERE/'sources/skeleton_horse-sheet.webp'))
    horse=Image.new('RGBA',(1254,1254));records=[]
    for n,(cell,box) in enumerate(mount_cells(source)):
        b=bounds(cell);sx,sy=HORSE_SEATS[n];sx+=n%3*418-box[0];sy+=n//3*418-box[1]
        tx,ty=REFERENCE_SEATS[n]
        scale=min((402-ty)/(b[3]-sy), (tx-6)/max(1,sx-b[0]), (412-tx)/max(1,b[2]-sx))
        ty=round(402+(sy-b[3])*scale,2)
        art=cell.crop(b).resize((round((b[2]-b[0])*scale),round((b[3]-b[1])*scale)),Image.Resampling.LANCZOS)
        x=round(tx+(b[0]-sx)*scale);y=402-bounds(art)[3]
        assert x>=1 and x+art.width<=417,(n,x,art.width)
        frame=Image.new('RGBA',(418,418));frame.alpha_composite(art,(x,y));horse.alpha_composite(frame,(n%3*418,n//3*418))
        records.append({'seat':[tx,ty],'bounds':bounds(frame),'scale':scale})
    save(horse,GAME/'assets/skeleton_horse_sprites.webp')
    source=clean(Image.open(HERE/'sources/troll_riding-sheet.webp'))
    # The six figures have a genuine inter-row gap; the lifted hand extends
    # across the nominal 512px division, so use the actual transparent gap.
    import numpy as np
    from build import gap_cut
    a=np.asarray(source.getchannel('A'))>8
    cut=gap_cut(a.any(axis=1),512,70)
    rider=Image.new('RGBA',(1254,836));rider_records=[]
    for n in range(6):
        row,col=divmod(n,3);y0=0 if row==0 else cut;y1=cut if row==0 else source.height
        strip=source.crop((0,y0,source.width,y1));occupied=(np.asarray(strip.getchannel('A'))>8).any(axis=0)
        xs=[0]+[gap_cut(occupied,n*512,90) for n in [1,2]]+[source.width]
        cell=strip.crop((xs[col],0,xs[col+1],strip.height));b=bounds(cell)
        assert b and min(b[:2])>0 and b[2]<cell.width and b[3]<cell.height,(n,b)
        hx,hy=TROLL_HIPS[n];hx+=col*512-xs[col];hy+=row*512-y0
        tx,ty=REFERENCE_SEATS[n+3] if row==0 else REFERENCE_SEATS[0]
        scale=.66
        art=cell.crop(b).resize((round((b[2]-b[0])*scale),round((b[3]-b[1])*scale)),Image.Resampling.LANCZOS)
        x=round(tx+(b[0]-hx)*scale);y=round(ty+(b[1]-hy)*scale)
        assert x>0 and y>0 and x+art.width<418 and y+art.height<418,(n,x,y,art.size)
        frame=Image.new('RGBA',(418,418));frame.alpha_composite(art,(x,y));rider.alpha_composite(frame,(col*418,row*418))
        hand=None
        if row:
            raw=[[435,230],[375,55],[420,210]][col]
            hand=[round(tx+(raw[0]-TROLL_HIPS[n][0])*scale,2),round(ty+(raw[1]-TROLL_HIPS[n][1])*scale,2)]
        rider_records.append({'hip':[tx,ty],'hand':hand,'bounds':bounds(frame),'scale':scale})
    save(rider,GAME/'assets/troll_riding_sprites.webp')
    data={'horse':records,'rider':rider_records}
    (HERE/'troll-alignment.json').write_text(json.dumps(data,indent=2)+'\n')
    (GAME/'troll-art.js').write_text('// Generated by tools/mounts/build_troll.py. Measured frame anchors.\nwindow.TROLL_ART = '+json.dumps(data,indent=2)+';\n')


if __name__=='__main__':build()
